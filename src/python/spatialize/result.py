import numpy as np
from matplotlib import pyplot as plt

from spatialize import SpatializeError, in_notebook
from spatialize.viz import plot_colormap_data, plot_histogram, PlotStyle

from typing import Optional, Dict, Any


class GridSearchResult:
    """Base class for the result of a hyperparameter grid search.

    Wraps the cross-validation error obtained for every combination of
    parameters evaluated during a grid search, and exposes convenience
    accessors for the best-scoring combination(s). Subclasses (e.g.
    :class:`~spatialize.gs.idw.IDWGridSearchResult`,
    :class:`~spatialize.gs.esi.ESIGridSearchResult`,
    :class:`~spatialize.gs.cat_esi.CatESIGridSearchResult`) implement
    :meth:`best_result` to return a dict ready to pass back to the
    corresponding estimation function via ``best_params_found``.

    Parameters
    ----------
    search_result_data : pandas.DataFrame
        One row per evaluated parameter combination, with a ``cv_error``
        column plus one column per searched hyperparameter.

    Attributes
    ----------
    search_result_data : pandas.DataFrame
        The raw per-combination results, as passed in.
    cv_error : pandas.DataFrame
        The ``cv_error`` column of `search_result_data`.
    best_params : pandas.DataFrame
        Subset of `search_result_data` whose ``cv_error`` equals the minimum
        observed value (there may be more than one row in case of ties).
    """
    def __init__(self, search_result_data):
        """Initialize the grid search result and derive the best-parameter subset.

        See the class docstring for parameter descriptions.
        """
        self.search_result_data = search_result_data

        data = self.search_result_data
        self.cv_error = data[['cv_error']]
        min_error = self.cv_error.min()['cv_error']
        self.best_params = data[data.cv_error <= min_error]

    def plot_cv_error(self,
                      theme: Optional[str] = 'alges',
                      color: Optional[str] = None,
                      fig_args: Optional[Dict[str, Any]] = None
                      ):
        """Plot the cross-validation errors of the hyperparameter search.

        The graph has two components: the first is the error histogram,
        and the second is the error level for each of the estimation scenarios
        generated by the gridded parameter search.

        Parameters
        ----------
        theme : str, optional
            Theme name. Available: ``'whitegrid'``, ``'darkgrid'``, ``'white'``,
            ``'dark'``, ``'alges'``, ``'minimal'``, ``'publication'``. Default:
            ``'alges'``.
        color : str, optional
            Color for the plots. If ``None``, uses the theme default or
            ``'skyblue'``.
        fig_args : dict, optional
            Dictionary with figure configuration for ``plt.subplots()``.
            Default assigns ``figsize=(10, 4)`` if not specified.

        Returns
        -------
        fig : matplotlib.figure.Figure
            The created figure.
        axes : tuple of matplotlib.axes.Axes
            The two axes ``(ax1, ax2)``: the error histogram and the error
            level plot.

        Raises
        ------
        ValueError
            If the specified theme does not exist.
        """
        # Default values for figsize if not specified
        if fig_args is None:
            fig_args = {'figsize': (10, 4)}
        elif 'figsize' not in fig_args:
            fig_args['figsize'] = (10, 4)

        with PlotStyle(theme=theme, color=color) as style:
            fig, (ax1, ax2) = plt.subplots(1, 2, **fig_args)
            plt.subplots_adjust(wspace=0.45)
            fig.suptitle("Cross Validation Error")

            plot_histogram(self.cv_error, ax1, style.color)

            self.cv_error.plot(kind='line',
                               ax=ax2,
                               y='cv_error',
                               xlabel="Search result data index",
                               ylabel="Error",
                               color=style.color,
                               lw=2,
                               legend=False)
            
            return fig, (ax1, ax2)

    def best_result(self, **kwargs):
        """Return the best-scoring parameter combination from the search.

        Not implemented on the base class; each subclass returns a dict
        of the parameters (plus any subclass-specific extras) ready to
        pass as ``best_params_found`` to the corresponding estimation
        function.

        Parameters
        ----------
        **kwargs
            Subclass-specific options.

        Returns
        -------
        dict
            The best parameter combination.

        Raises
        ------
        NotImplementedError
            Always, on the base class. Subclasses must override this method.
        """
        raise NotImplementedError

    def save(self, path):
        """Persist this grid search result to `path`.

        Not implemented on the base class.

        Parameters
        ----------
        path : str
            Destination path.

        Raises
        ------
        NotImplementedError
            Always, on the base class. Subclasses must override this method.
        """
        raise NotImplementedError

    def load(self, path):
        """Load a grid search result previously saved with :meth:`save`.

        Not implemented on the base class.

        Parameters
        ----------
        path : str
            Path to load from.

        Raises
        ------
        NotImplementedError
            Always, on the base class. Subclasses must override this method.
        """
        raise NotImplementedError


class EstimationResult:
    """Base class for the result of a spatial estimation at a set of locations.

    Wraps the estimated values at the interpolation locations `xi` together
    with enough information to reshape them back to a grid, plot them, and
    (when the original observed data was supplied) support further analyses
    that need it. Subclasses (e.g. :class:`~spatialize.gs.idw.IDWResult`,
    :class:`~spatialize.gs.esi.ESIResult`,
    :class:`~spatialize.gs.cat_esi.CatESIResult`) add estimator-specific
    functionality such as ensembles and precision metrics.

    Parameters
    ----------
    estimation : array_like
        Estimated values, flattened to 1D of length $N_{x^*}$ even when
        `griddata` is ``True``.
    griddata : bool, optional
        Whether `xi` is grid-shaped. Default: ``False``.
    original_shape : tuple, optional
        Shape to reshape `estimation` back into when `griddata` is
        ``True``.
    xi : array_like, optional
        The interpolation locations (grid-shaped tuple/array if `griddata`
        is ``True``, otherwise an $N_{x^*} \times D$ array). Used to infer
        plot extents and, for gridded data, to flatten locations.
    points : array_like, optional
        The original observed sample locations, if available. Used e.g. to
        calibrate ensemble widening against a spatial target variance.
    values : array_like, optional
        The original observed sample values, if available, used together
        with `points`.

    Attributes
    ----------
    griddata : bool
        Whether `xi` is grid-shaped.
    original_shape : tuple or None
        Shape used to reshape `estimation` for grid data.
    points : array_like or None
        The original observed sample locations, if provided.
    values : array_like or None
        The original observed sample values, if provided.
    """
    def __init__(self, estimation, griddata=False, original_shape=None, xi=None,
                 points=None, values=None):
        """Initialize the result with an estimate and its supporting metadata.

        See the class docstring for parameter descriptions.
        """
        self._estimation = estimation
        self.griddata = griddata
        self.original_shape = original_shape
        self._xi = xi
        # original observed data (when available), used e.g. to calibrate ensemble
        # widening against a spatial target variance
        self.points = points
        self.values = values

    def estimation(self):
        """Return the estimated values at locations `xi`.

        Returns
        -------
        estimation : numpy.ndarray
            An array of dimension $N_{x^*}$, for non-gridded data, and of
            dimension $d_1 \times d_2$ for gridded data -- remember that,
            in this case, $d_1 \times d_2 = N_{x^*}$.
        """
        if self.griddata:
            return self._estimation.reshape(self.original_shape)
        else:
            return self._estimation

    def _get_extent(self):
        """Returns [x_min, x_max, y_min, y_max] for 2D spatial data, or None otherwise."""
        if self._xi is None:
            return None
        if self.griddata:
            # xi may be a tuple/list of arrays or an ndarray; use len() for dimension count
            if len(self._xi) != 2:
                return None
            x_min, x_max = self._xi[0].min(), self._xi[0].max()
            y_min, y_max = self._xi[1].min(), self._xi[1].max()
        else:
            if self._xi.shape[-1] != 2:
                return None
            x_min, x_max = self._xi[:, 0].min(), self._xi[:, 0].max()
            y_min, y_max = self._xi[:, 1].min(), self._xi[:, 1].max()
        return [x_min, x_max, y_min, y_max]

    def plot_estimation(self, ax=None, w=None, h=None, theme='alges', cmap=None, **imshow_args):
        """
        Plots the estimation using `matplotlib`.

        Parameters
        ----------
        ax :  (`matplotlib.axes.Axes`, optional)
            The `Axes` object to render the plot on. If `None`, a new `Axes` object is created.
        w : (int, optional)
            The width of the image (if the data is reshaped).
        h : (int, optional)
            The height of the image (if the data is reshaped).
        theme : (str, optional)
            Theme name. Available: 'whitegrid', 'darkgrid', 'white', 'dark',
            'alges', 'minimal', 'publication'
        cmap : (str, optional)
            Colormap for the plot. If None, uses theme default or 'coolwarm'
        **imshow_args : (optional)
            Additional keyword arguments passed to the `_plot_data` function (e.g., vmin, vmax, alpha).

        """
        plot_imshow_args = imshow_args.copy()
        if not cmap:
            cmap = plot_imshow_args.pop('cmap', None)
        if 'extent' not in plot_imshow_args:
            extent = self._get_extent()
            if extent is not None:
                plot_imshow_args['extent'] = extent

        with PlotStyle(theme=theme, cmap=cmap) as style:
            self._plot_data(self.estimation(), ax, w, h, cmap = style.cmap, **plot_imshow_args)

    def _plot_data(self, data, ax=None, w=None, h=None, **imshow_args):
        plot_colormap_data(data, ax=ax, w=w, h=h, xi_locations=self._xi, griddata=self.griddata, **imshow_args)

    def quick_plot(self, w=None, h=None, **imshow_args):
        """
        Quickly plots the estimation using `matplotlib`.

        Parameters
        ----------
        w : (int, optional)
            The width of the image (if the data is reshaped).
        h : (int, optional)
            The height of the image (if the data is reshaped).
        **imshow_args : (optional)
            Additional keyword arguments passed to the figure creation (e.g., DPI, figure size).
        """
        if self._xi is not None:
            if self.griddata:
                if len(self._xi) > 2:
                    raise SpatializeError("quick_plot() for 3D+ data is not supported")
            else:
                if self._xi.shape[1] > 2:
                    raise SpatializeError("quick_plot() for 3D data is not supported")

        fig = plt.figure(dpi=150, **imshow_args)
        gs = fig.add_gridspec(1, 1, wspace=0.45)
        ax = gs.subplots()

        ax.set_title('Estimation')
        self.plot_estimation(ax, w=w, h=h)
        ax.set_aspect('equal')

        if not in_notebook():
            return fig

    def __repr__(self):
        min, max = np.nanmin(self.estimation()), np.nanmax(self.estimation())
        m, s, med = np.nanmean(self.estimation()), np.nanstd(self.estimation()), np.nanmedian(self.estimation())
        msg = (f"estimation results: \n"
               f"  minimum: {min:.3f}, maximum: {max:.3f}\n"
               f"  mean: {m:.2f}, std dev: {s:.2f}, median: {med:.2f}\n"
               f"to display the result, use the method ‘quick_plot()’.\n")
        return msg
